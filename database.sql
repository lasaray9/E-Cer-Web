CREATE DATABASE IF NOT EXISTS school_certificates CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE school_certificates;
CREATE TABLE IF NOT EXISTS media (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 filename VARCHAR(80) NOT NULL UNIQUE,
 mime VARCHAR(30) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS projects (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 school VARCHAR(200) NOT NULL,
 award VARCHAR(200) NOT NULL DEFAULT 'ได้เข้าร่วมกิจกรรม',
 certificate_date DATE NOT NULL,
 signer_name VARCHAR(150) NOT NULL,
 signer_position VARCHAR(150) NOT NULL,
 number_prefix VARCHAR(20) NOT NULL DEFAULT 'SCH',
 background_id INT UNSIGNED NULL,
 signature_id INT UNSIGNED NULL,
 layout_json TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (background_id) REFERENCES media(id),
 FOREIGN KEY (signature_id) REFERENCES media(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS recipients (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id INT UNSIGNED NOT NULL,
 full_name VARCHAR(200) NOT NULL,
 classroom VARCHAR(80) NOT NULL DEFAULT '',
 certificate_number VARCHAR(60) NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (project_id) REFERENCES projects(id),
 INDEX idx_project (project_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
